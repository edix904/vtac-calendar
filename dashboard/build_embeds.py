#!/usr/bin/env python3
"""Write the generated Apps Script files for the Calendar Dashboard:

  NormaliseRules.js  PD_RULES_EMBEDDED: fallback copy of principal_dates_rules.json
  CampusBackfill.js  CAMPUS_BACKFILL: backfill/monash_my_id_backfill.csv as rows

Usage: python dashboard/build_embeds.py --version 2026-10-20 [--out dashboard-script]
Then copy dashboard/Normalise.js and dashboard/PrincipalDates.js alongside and `clasp push`.
"""
import argparse
import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", required=True, help="backfill version; changing it re-seeds the Backfill tab rows")
    ap.add_argument("--out", default=os.path.join(ROOT, "dashboard-script"))
    a = ap.parse_args()
    with open(os.path.join(ROOT, "principal_dates_rules.json"), encoding="utf-8") as f:
        rules = json.load(f)
    with open(os.path.join(a.out, "NormaliseRules.js"), "w", encoding="utf-8") as f:
        f.write("/**\n * GENERATED by dashboard/build_embeds.py from principal_dates_rules.json in\n"
                " * https://github.com/edix904/vtac-calendar. Used only when GitHub can't be reached;\n"
                " * the sync normally fetches the live rules file (PD_RULES_URL in Normalise.js).\n */\n")
        f.write("const PD_RULES_EMBEDDED = " + json.dumps(rules, ensure_ascii=False, indent=1) + ";\n")
    with open(os.path.join(ROOT, "backfill", "monash_my_id_backfill.csv"), encoding="utf-8") as f:
        rows = list(csv.reader(f))[1:]
    with open(os.path.join(a.out, "CampusBackfill.js"), "w", encoding="utf-8") as f:
        f.write("/**\n * Monash Malaysia / Indonesia principal dates history, GENERATED by dashboard/build_embeds.py\n"
                " * from backfill/monash_my_id_backfill.csv (principal_dates_backfill.py) in\n"
                " * https://github.com/edix904/vtac-calendar. Titles match the live .ics feeds.\n"
                " * Synced into the Backfill tab by syncEmbeddedBackfill_(): rows whose Source starts with\n"
                " * CAMPUS_BACKFILL_SOURCE are replaced whenever CAMPUS_BACKFILL_VERSION changes.\n"
                " * [Calendar Name, Title, Start Date, End Date (incl.), Source, Source URL]\n */\n")
        f.write(f"const CAMPUS_BACKFILL_VERSION = {json.dumps(a.version)};\n")
        f.write("const CAMPUS_BACKFILL_SOURCE = 'MY/ID principal dates page';\n")
        f.write("const CAMPUS_BACKFILL = [\n")
        for r in rows:
            f.write("  " + json.dumps(r, ensure_ascii=False) + ",\n")
        f.write("];\n")
    print(f"wrote NormaliseRules.js and CampusBackfill.js ({len(rows)} rows) to {a.out}")


if __name__ == "__main__":
    main()
